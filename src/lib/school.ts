/** حداکثر طول مجاز نام شعبه */
export const BRANCH_MAX = 30

const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹'

/** تبدیل ارقام لاتین/عربی به ارقام فارسی (نمایش یکدست «هفتم ۷۰۳») */
export function toPersianDigits(s: string): string {
  return s
    .replace(/[0-9]/g, (d) => FA_DIGITS[Number(d)])
    .replace(/[\u0660-\u0669]/g, (d) => FA_DIGITS[d.charCodeAt(0) - 0x0660])
}

/** الگوی نام کلاس: «پایه + شعبه» — ارقام شعبه فارسی می‌شوند */
export function composeClassName(grade: string, branch: string): string {
  return `${grade} ${toPersianDigits(branch.trim())}`.replace(/\s+/g, ' ').trim()
}

/** الگوی نام گروه درسی: «درس + نام کلاس» — مثلاً «ریاضی هفتم ۷۰۳» */
export function composeGroupName(subject: string, className: string): string {
  return `${subject.trim()} ${className.trim()}`.replace(/\s+/g, ' ').trim()
}
